"""
Report Agent: generates a full scientific-style report card after pipeline completion.
Produces HTML and PDF output. Includes QC plots, variant stats, gene counts, etc.
"""

import os
import json
from pathlib import Path
from typing import Optional
from datetime import datetime
import anthropic
from jinja2 import Environment, FileSystemLoader


SYSTEM_PROMPT = """You are a clinical bioinformatics report writer.
Generate professional, concise report summaries based on pipeline QC metrics and results.
Use precise scientific language. Flag any QC failures prominently.
Output JSON with report sections."""

REPORT_PROMPT = """Generate a bioinformatics analysis report for:

Analysis type: {analysis_type}
Sample IDs: {samples}
Reference genome: {reference}
Pipeline steps completed: {steps_completed}
QC metrics: {qc_metrics}
Result summary: {result_summary}
Run date: {run_date}

Return JSON:
{{
  "executive_summary": "2-3 sentence summary for non-bioinformaticians",
  "qc_status": "PASS|WARN|FAIL",
  "qc_flags": ["list of QC issues"],
  "sections": [
    {{
      "title": "Quality Control",
      "content": "markdown text",
      "metrics_table": [{{"metric": "...", "value": "...", "threshold": "...", "status": "PASS|FAIL"}}]
    }}
  ],
  "clinical_interpretation": "interpretation relevant to analysis type",
  "recommendations": ["list of follow-up recommendations"],
  "methods_text": "Methods section ready to copy into a publication"
}}"""


