class ReportAgent:
    def __init__(self, api_key: Optional[str] = None):
        self.client = anthropic.Anthropic(api_key=api_key or os.environ["ANTHROPIC_API_KEY"])

    def generate(
        self,
        pipeline: dict,
        qc_metrics: dict,
        result_summary: dict,
        output_dir: Path,
        sample_ids: list[str],
    ) -> dict:
        """Generate HTML (and optionally PDF) report. Saves to output_dir."""
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        prompt = REPORT_PROMPT.format(
            analysis_type=pipeline.get("analysis_type", "unknown"),
            samples=", ".join(sample_ids),
            reference=json.dumps(pipeline.get("reference_genome", {})),
            steps_completed=", ".join(
                s.get("name", "") for s in pipeline.get("steps", [])
            ),
            qc_metrics=json.dumps(qc_metrics, indent=2)[:3000],
            result_summary=json.dumps(result_summary, indent=2)[:3000],
            run_date=datetime.now().strftime("%Y-%m-%d %H:%M"),
        )

        response = self.client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=4096,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": prompt}]
        )

        import re
        content = response.content[0].text.strip()
        content = re.sub(r'^```[a-z]*\n?', '', content)
        content = re.sub(r'\n?```$', '', content)

        try:
            report_data = json.loads(content)
        except json.JSONDecodeError:
            match = re.search(r'\{[\s\S]+\}', content)
            report_data = json.loads(match.group()) if match else {}

        # Add metadata
        report_data["title"] = f"{pipeline.get('analysis_type', 'Genomic')} Analysis Report"
        report_data["analysis_type"] = pipeline.get("analysis_type", "unknown")
        report_data["run_date"] = datetime.now().strftime("%Y-%m-%d %H:%M")
        report_data["samples"] = sample_ids

        # Render HTML
        from jinja2 import Template
        template = Template(REPORT_HTML_TEMPLATE)
        html = template.render(report=report_data)

        html_path = output_dir / "report.html"
        html_path.write_text(html, encoding="utf-8")

        # Save JSON
        json_path = output_dir / "report.json"
        json_path.write_text(json.dumps(report_data, indent=2))

        # Try PDF generation (optional, requires weasyprint)
        pdf_path = None
        try:
            from weasyprint import HTML
            pdf_path = output_dir / "report.pdf"
            HTML(string=html).write_pdf(str(pdf_path))
        except ImportError:
            pass  # weasyprint not installed, HTML only

        return {
            "html": str(html_path),
            "pdf": str(pdf_path) if pdf_path else None,
            "json": str(json_path),
            "qc_status": report_data.get("qc_status", "UNKNOWN"),
        }
